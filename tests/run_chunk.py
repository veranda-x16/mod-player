#!/usr/bin/env python3
"""
Render-loop regression: does the player still take the identical path through
the sample data?

Runs the -DCHUNK_TRACE build (tests/t_chunk.c) over a fixed set of modules and
compares the resulting chunk hash against tests/golden/chunk_hashes.txt. The
hash covers every chunk's frame count, all four voice phases and all four read
positions, so an unchanged hash means bit-identical audio -- something a WAV
capture cannot establish, because the emulator's FIFO drain follows the host
audio device and two captures of one binary differ in ~0.09% of frames.

  python3 tests/run_chunk.py            check against the golden file
  python3 tests/run_chunk.py --update   record the current hashes as golden

The synthetic modules are generated by "make mods" and are always present. The
real ones are not ours to redistribute, so a missing module is reported and
skipped rather than failing the run.
"""
import os
import subprocess
import sys
import tempfile
import shutil

EMU = os.environ.get("X16EMU", os.path.expanduser("~/Projects/x16-emulator/build/x16emu"))
ROM = os.environ.get("X16ROM", os.path.expanduser("~/Projects/x16-rom/build/x16/rom.bin"))
PRG = "build/T_CHUNK.PRG"
GOLDEN = "tests/golden/chunk_hashes.txt"
TIMEOUT = 300

# The synthetic pair first: "make mods" always generates these, so the gate
# still bites on a clean checkout. Real modules are not ours to redistribute
# and are skipped when absent -- but they are the ones with short
# non-power-of-two loops (the cache_consume fast path), long samples, and
# enough patterns to cross a pattern bank, so keep them where they exist.
MODULES = [
    "tests/mods/sampleloop.mod",
    "tests/mods/fourvoice.mod",
    "tests/mods/real/Checknob.mod",
    "tests/mods/real/JESTER - Stardust Memories.mod",
    "tests/mods/real/JOGEIR LILJEDAHL - G-Comp.mod",
    "modp/Cracktro/DIZZYCRS.MOD",
    "modp/Demos/Mod.kaffe Og Kage.mod",
]


def run(mod):
    d = tempfile.mkdtemp()
    try:
        shutil.copy(PRG, os.path.join(d, "T.PRG"))
        shutil.copy(mod, os.path.join(d, "music.mod"))
        env = dict(os.environ, SDL_VIDEODRIVER="dummy", SDL_AUDIODRIVER="dummy")
        with open(os.path.join(d, "raw.txt"), "wb") as out:
            p = subprocess.Popen(
                [EMU, "-rom", ROM, "-ram", "2048", "-prg", "T.PRG", "-run", "-warp"],
                cwd=d, stdout=out, stderr=subprocess.STDOUT, env=env)
            # The emulator has no guest-triggered quit, so poll for the final
            # line and stop as soon as it appears.
            import time
            deadline = time.time() + TIMEOUT
            while time.time() < deadline:
                if p.poll() is not None:
                    break
                with open(os.path.join(d, "raw.txt")) as f:
                    if any(l.startswith("done ") for l in f):
                        break
                time.sleep(1)
            p.kill()
            p.wait()
        with open(os.path.join(d, "raw.txt")) as f:
            for line in f:
                if line.startswith("done "):
                    parts = line.split()
                    return "%s %s" % (parts[1], parts[2])   # chunks, hash
        return None
    finally:
        shutil.rmtree(d, ignore_errors=True)


def main():
    update = "--update" in sys.argv
    if not os.path.exists(PRG):
        sys.exit("%s missing -- run: make %s" % (PRG, PRG))

    golden = {}
    if os.path.exists(GOLDEN):
        for line in open(GOLDEN):
            line = line.strip()
            if line and not line.startswith("#"):
                k, v = line.split("|", 1)
                golden[k.strip()] = v.strip()

    results, fails, skips = {}, 0, 0
    for mod in MODULES:
        if not os.path.exists(mod):
            print("  skip  %s (not present)" % os.path.basename(mod))
            skips += 1
            continue
        got = run(mod)
        if got is None:
            print("  FAIL  %s -- no completion in %ds" % (os.path.basename(mod), TIMEOUT))
            fails += 1
            continue
        results[mod] = got
        if update:
            print("  rec   %-40s %s" % (os.path.basename(mod), got))
        elif mod not in golden:
            print("  new   %-40s %s (no golden entry)" % (os.path.basename(mod), got))
        elif golden[mod] == got:
            print("  ok    %-40s %s" % (os.path.basename(mod), got))
        else:
            print("  FAIL  %-40s got %s want %s"
                  % (os.path.basename(mod), got, golden[mod]))
            fails += 1

    if update:
        with open(GOLDEN, "w") as f:
            f.write("# Chunk-decision hashes: see tests/run_chunk.py.\n"
                    "# Regenerate deliberately (--update), never to make a red test green.\n")
            for mod in MODULES:
                if mod in results:
                    f.write("%s | %s\n" % (mod, results[mod]))
        print("\nrecorded %d hashes to %s" % (len(results), GOLDEN))
        return 0

    print("\n%d checked, %d differ, %d skipped" % (len(results), fails, skips))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
