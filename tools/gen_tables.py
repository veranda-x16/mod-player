#!/usr/bin/env python3
"""
Generate src/tables.s for a chosen output rate.

Two tables:

volume  17 page-aligned pages of 256 bytes, indexed [volume/4][sample_byte].
        Entry = (int8)sample * volume / 128. The /128 rather than /64 gives
        each voice a range of -64..63, so two hard-panned voices sum to
        -128..126 -- exactly int8, so the mixer needs no clamp. The mixer
        selects a page by self-modifying the high byte of a "lda $xx00,y",
        which makes a volume change free at mix time and costs no table
        rebuild.

        Stored at 4-unit granularity (17 pages, 4,352 bytes) rather than all
        65 levels. The full table cost 16,640 bytes -- 43% of fixed RAM -- and
        RAM, not CPU, is what limits this player: a UI has to come out of the
        same 38.6 KB. Two units out of 64 is about 0.27 dB, which is inaudible
        on MOD content, and volume changes stay free at mix time.

period  step = 7093789.2 / (2 * P * F) in 8.16 fixed point (PAL Amiga clock),
        indexed directly by period. ProTracker effects produce arbitrary
        periods between notes, so a 60-entry note table will not do; a direct
        table removes division from the runtime entirely. Stored as three
        parallel byte planes so an entry is three indexed loads.
"""
import argparse

PAL_CLOCK = 7093789.2
VERA_UNIT = 25_000_000 / 512 / 128      # Hz per AUDIO_RATE step
PERIOD_MIN, PERIOD_MAX = 113, 907       # ProTracker range incl. finetune


def emit(out, rate_value):
    hz = rate_value * VERA_UNIT
    lines = []
    A = lines.append
    A("; GENERATED by tools/gen_tables.py -- do not edit.")
    A("; AUDIO_RATE=%d -> %.2f Hz output." % (rate_value, hz))
    A("")
    A("        .export voltab, steptab_lo, steptab_hi, steptab_int")
    A("        ; STEP_PERIOD_MIN/MAX live in src/x16.inc: they are a property")
    A("        ; of ProTracker, not of this generated file.")
    A('        .include "x16.inc"')
    A("")
    A('        .segment "ALIGNDATA"')
    A("; --- volume: 17 pages of 256, page-aligned, step of 4 -------------")
    A("VOLTAB_PAGES = 17")
    A("voltab:")
    for i in range(17):
        v = i * 4
        row = []
        for b in range(256):
            s = b - 256 if b >= 128 else b        # byte -> int8
            row.append((s * v // 128) & 0xFF)
        A("        ; volume %d" % v)
        for i in range(0, 256, 16):
            A("        .byte " + ",".join("$%02X" % x for x in row[i:i + 16]))
    A("")

    steps = []
    for p in range(PERIOD_MIN, PERIOD_MAX + 1):
        steps.append(int(round(PAL_CLOCK * 65536 / (2 * p * hz))) & 0xFFFFFF)

    # A segment of its own: read only when a period is set (about 200 times
    # a second), so a host short of fixed RAM may place it in a RAM bank
    # (Veranda: a banked overlay; mixer_api.s maps mod_tab_bank).
    A('        .segment "STEPTAB"')
    A("; --- period -> 8.16 step, indexed by (period - %d) ------------------"
      % PERIOD_MIN)
    for name, shift in (("steptab_lo", 0), ("steptab_hi", 8), ("steptab_int", 16)):
        A("%s:" % name)
        vals = [(s >> shift) & 0xFF for s in steps]
        for i in range(0, len(vals), 16):
            A("        .byte " + ",".join("$%02X" % x for x in vals[i:i + 16]))
    A("")
    open(out, "w").write("\n".join(lines) + "\n")

    print("%s: rate=%d (%.2f Hz), %d periods, volume table 17x256=%d bytes"
          % (out, rate_value, hz, len(steps), 17 * 256))
    print("  step at period 428 (C-2) = %.6f  (0x%06X)"
          % (steps[428 - PERIOD_MIN] / 65536.0, steps[428 - PERIOD_MIN]))
    print("  step at period 113 (max) = %.6f  (0x%06X)"
          % (steps[113 - PERIOD_MIN] / 65536.0, steps[113 - PERIOD_MIN]))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--rate", type=int, default=42)
    ap.add_argument("--out", default="src/tables.s")
    a = ap.parse_args()
    emit(a.out, a.rate)
