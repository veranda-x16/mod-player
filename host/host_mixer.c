/*
 * host_mixer.c -- bit-exact C model of src/mixer.s.
 *
 * The X16 mixer is hand-written assembly with no host twin, so correctness is
 * checked by rendering the same inputs through both and comparing byte for
 * byte. This model must therefore reproduce the assembly's arithmetic
 * exactly, including the parts that are only "correct" by construction:
 *
 *   - the phase integer is a single byte, so it wraps mod 256 (the carry out
 *     of "adc st+2" is discarded). That wrap IS the 256-byte cache loop.
 *   - the mix is "clc / adc", i.e. 8-bit wraparound addition. In real use the
 *     cache holds (sample*volume)/128 so sums stay inside int8 and never wrap,
 *     but the model must wrap anyway or it would disagree with the hardware on
 *     the deliberately out-of-range test vectors.
 *
 * stdin:  4 * 256 cache bytes, then 4 * 3 step bytes (frac_lo, frac_hi, int),
 *         then 4 volume bytes (0..64), all in voice order 0,1,2,3.
 * stdout: 256 bytes = 128 stereo frames, <left><right>.
 */

#include <stdint.h>
#include <stdio.h>

#define FRAMES 128

/* The volume table is generated by tools/gen_tables.py with Python's floor
   division. C truncates toward zero, which differs for negative samples
   (-1*1/128 is -1 floored but 0 truncated), so the model has to floor too or
   it disagrees with the hardware on every quiet negative sample. */
static int floor_div(int a, int b)
{
    int q = a / b;
    if ((a % b != 0) && ((a < 0) != (b < 0)))
        q--;
    return q;
}

/* voltab[v][b] = (int8)b * v / 128, giving each voice -64..63 so that two
   hard-panned voices sum to exactly int8.

   The table stores every fourth volume level (17 pages, not 65) to keep 4 KB
   of fixed RAM free, and the mixer picks its page with (v + 2) >> 2 -- so the
   effective volume is v rounded to the nearest multiple of four. */
static uint8_t vol_scale(uint8_t b, uint8_t v)
{
    int s = (b >= 128) ? (int)b - 256 : (int)b;
    int veff = ((v + 2) >> 2) * 4;
    return (uint8_t)(floor_div(s * veff, 128) & 0xFF);
}

int main(void)
{
    uint8_t  cache[4][256];
    uint32_t step[4] = {0};
    uint32_t phase[4] = {0};
    uint8_t  vol[4];
    uint8_t  out[FRAMES * 2];

    if (fread(cache, 1, sizeof cache, stdin) != sizeof cache)
        return fprintf(stderr, "short cache read\n"), 1;

    for (int v = 0; v < 4; v++) {
        uint8_t b[3];
        if (fread(b, 1, 3, stdin) != 3)
            return fprintf(stderr, "short step read\n"), 1;
        step[v] = (uint32_t)b[0] | ((uint32_t)b[1] << 8) | ((uint32_t)b[2] << 16);
    }

    if (fread(vol, 1, 4, stdin) != 4)
        return fprintf(stderr, "short volume read\n"), 1;

    for (int i = 0; i < FRAMES; i++) {
        uint8_t s[4];
        for (int v = 0; v < 4; v++) {
            /* 8.16 phase; the integer byte wraps, matching the discarded carry */
            phase[v] = (phase[v] + step[v]) & 0xFFFFFF;
            s[v] = vol_scale(cache[v][(phase[v] >> 16) & 0xFF], vol[v]);
        }
        out[i * 2 + 0] = (uint8_t)(s[0] + s[3]);   /* L = ch1 + ch4 */
        out[i * 2 + 1] = (uint8_t)(s[1] + s[2]);   /* R = ch2 + ch3 */
    }

    fwrite(out, 1, sizeof out, stdout);
    return 0;
}
